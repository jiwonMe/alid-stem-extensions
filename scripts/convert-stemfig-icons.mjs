import { readFileSync, readdirSync, writeFileSync } from 'node:fs';
import { homedir } from 'node:os';
import { join } from 'node:path';

/**
 * Converts the stemdraw UI icons that its plugins name (tools, layers) into alid
 * contributed-icon path data: src/stemfig-icons.ts.
 *
 *   node scripts/convert-stemfig-icons.mjs [path-to-stemdraw]
 *
 * Each icon is an 18×18 outline (Nucleo UI outline grid, or stemdraw's own symbols
 * on that grid). Elements become path data; filled dots keep `fill: true`.
 */
const stemdraw = process.argv[2] ?? process.env.STEMDRAW ?? join(homedir(), 'Workspace', 'stemdraw');
const icons = join(stemdraw, 'packages/ui/src/icons');
const registry = readFileSync(join(icons, 'registry.ts'), 'utf8');

const files = new Map();
for (const dir of ['custom', 'nucleo']) for (const file of readdirSync(join(icons, dir))) files.set(file.replace(/\.tsx$/, ''), join(icons, dir, file));

const n = value => Number(value);
const fmt = value => String(Math.round(value * 1000) / 1000);
const attrs = source => Object.fromEntries([...source.matchAll(/([\w-]+)=(?:"([^"]*)"|\{([^}]*)\})/g)].map(([, k, a, b]) => [k, a ?? b]));

function toPath(tag, a) {
  switch (tag) {
    case 'path': return a.d;
    case 'line': return `M${fmt(n(a.x1))} ${fmt(n(a.y1))}L${fmt(n(a.x2))} ${fmt(n(a.y2))}`;
    case 'polyline': case 'polygon': {
      const pts = a.points.trim().split(/[\s,]+/).map(Number);
      let d = `M${fmt(pts[0])} ${fmt(pts[1])}`;
      for (let i = 2; i < pts.length; i += 2) d += `L${fmt(pts[i])} ${fmt(pts[i + 1])}`;
      return tag === 'polygon' ? `${d}Z` : d;
    }
    case 'circle': {
      const cx = n(a.cx), cy = n(a.cy), r = n(a.r);
      return `M${fmt(cx - r)} ${fmt(cy)}a${fmt(r)} ${fmt(r)} 0 1 0 ${fmt(2 * r)} 0a${fmt(r)} ${fmt(r)} 0 1 0 ${fmt(-2 * r)} 0Z`;
    }
    case 'rect': {
      let x = n(a.x), y = n(a.y);
      const w = n(a.width), h = n(a.height), r = Math.min(n(a.rx ?? a.ry ?? 0), w / 2, h / 2);
      // The only rotated rect (sidebar) is a 180° turn about (9,9); fold it into the coordinates.
      if (a.transform) { const m = /translate\((\S+) (\S+)\) rotate\(180\)/.exec(a.transform); if (!m) throw new Error(`Unsupported transform ${a.transform}`); x = n(m[1]) - x - w; y = n(m[2]) - y - h; }
      if (!r) return `M${fmt(x)} ${fmt(y)}h${fmt(w)}v${fmt(h)}h${fmt(-w)}Z`;
      return `M${fmt(x + r)} ${fmt(y)}h${fmt(w - 2 * r)}a${fmt(r)} ${fmt(r)} 0 0 1 ${fmt(r)} ${fmt(r)}v${fmt(h - 2 * r)}a${fmt(r)} ${fmt(r)} 0 0 1 ${fmt(-r)} ${fmt(r)}h${fmt(-(w - 2 * r))}a${fmt(r)} ${fmt(r)} 0 0 1 ${fmt(-r)} ${fmt(-r)}v${fmt(-(h - 2 * r))}a${fmt(r)} ${fmt(r)} 0 0 1 ${fmt(r)} ${fmt(-r)}Z`;
    }
  }
  throw new Error(`Unsupported element <${tag}>`);
}

function convert(component) {
  const file = files.get(component);
  if (!file) throw new Error(`Missing icon component ${component}`);
  const source = readFileSync(file, 'utf8');
  if (!/viewBox="0 0 18 18"/.test(source)) throw new Error(`${component} is not on the 18 grid`);
  const out = [];
  for (const [, tag, body] of source.matchAll(/<(path|line|polyline|polygon|circle|rect)\b([^>]*?)\/?>/g)) {
    const a = attrs(body);
    const filled = a.fill === 'currentColor';
    if (!filled && a.stroke !== 'currentColor') throw new Error(`${component}: <${tag}> is neither stroked nor filled`);
    const d = toPath(tag, a).replace(/\s+/g, ' ').trim();
    out.push(filled ? { d, fill: true } : d);
  }
  if (!out.length) throw new Error(`${component}: no shapes`);
  return out;
}

const names = Object.fromEntries([...registry.matchAll(/^\s+(\w+): (\w+Outline18),$/gm)].map(([, key, component]) => [key, component]));
const wanted = process.env.ICONS?.split(',') ?? Object.keys(names);
const result = {};
for (const key of wanted) result[key] = { size: 18, paths: convert(names[key]) };

const body = Object.entries(result).map(([key, icon]) => `  ${key}: ${JSON.stringify(icon)},`).join('\n');
writeFileSync(new URL('../src/stemfig-icons.ts', import.meta.url), `// Generated by scripts/convert-stemfig-icons.mjs from stemdraw packages/ui/src/icons.
// Nucleo UI outline 18px (licensed with stemdraw's Nucleo set) and stemdraw's own symbols on that grid.
// Do not edit by hand; re-run the script.
import type { WorkbenchIcon } from "./alid.ts";

export const stemfigIcons: Record<string, WorkbenchIcon> = {
${body}
};
`);
console.log(`Wrote ${Object.keys(result).length} icons.`);
